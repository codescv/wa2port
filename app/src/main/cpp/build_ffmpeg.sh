#!/usr/bin/env bash
# Reproducible build of a minimal LGPL FFmpeg for the WA2 movie player.
#
# Only what the original movies (mvNN0.pak = raw ASF, WMV3 Main video + WMA v2 audio) need:
#   demuxer asf, decoders wmv3/vc1/wmav2, protocol file, swscale, swresample.
#   The h263 decoder is enabled only to satisfy a configure dependency gap in 7.0.x: vc1 selects
#   intrax8 -> msmpeg4data.o, which references ff_mpeg4_intra_* / ff_inter_* tables that are only
#   built with h263 (mpeg4video.o, h263data.o). Without it libavcodec.so has undefined symbols.
# Output: shared libs + headers in app/src/main/cpp/ffmpeg/<abi>/{lib,include}.
#
# Usage: app/src/main/cpp/build_ffmpeg.sh [abi...]      (default: arm64-v8a x86_64)
# Env:   ANDROID_NDK_HOME (default ~/Android/Sdk/ndk/27.0.12077973)
#        WA2_FFMPEG_CACHE (default ~/.cache/wa2port-ffmpeg; tarball + build trees live here)
#        JOBS             (default nproc)
#
# The source tarball and build trees stay outside the repository. Note that the repository's
# .gitignore ignores *.so, so the prebuilt libraries must be added with `git add -f`.
set -euo pipefail

FFMPEG_VERSION=7.0.2
FFMPEG_SHA256=8646515b638a3ad303e23af6a3587734447cb8fc0a0c064ecdb8e95c4fd8b389
API=26  # == minSdk

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT_ROOT="$SCRIPT_DIR/ffmpeg"
NDK="${ANDROID_NDK_HOME:-$HOME/Android/Sdk/ndk/27.0.12077973}"
CACHE="${WA2_FFMPEG_CACHE:-$HOME/.cache/wa2port-ffmpeg}"
JOBS="${JOBS:-$(nproc)}"
TC="$NDK/toolchains/llvm/prebuilt/linux-x86_64"

[[ -x "$TC/bin/clang" ]] || { echo "NDK toolchain not found at $TC" >&2; exit 1; }
mkdir -p "$CACHE"

# --- fetch + verify source -------------------------------------------------------------------
TARBALL="$CACHE/ffmpeg-$FFMPEG_VERSION.tar.xz"
if [[ ! -f "$TARBALL" ]]; then
  curl -fL --retry 3 -o "$TARBALL.part" "https://ffmpeg.org/releases/ffmpeg-$FFMPEG_VERSION.tar.xz"
  mv "$TARBALL.part" "$TARBALL"
fi
echo "$FFMPEG_SHA256  $TARBALL" | sha256sum -c -
SRC="$CACHE/ffmpeg-$FFMPEG_VERSION"
if [[ ! -f "$SRC/configure" ]]; then
  tar -xJf "$TARBALL" -C "$CACHE"
fi

# --- per-ABI build ---------------------------------------------------------------------------
build_abi() {
  local abi="$1" arch cpu triple extra=()
  case "$abi" in
    arm64-v8a) arch=aarch64; cpu=armv8-a; triple=aarch64-linux-android ;;
    # No nasm/yasm dependency: external x86 asm is disabled (inline asm + C paths remain).
    x86_64)    arch=x86_64;  cpu=x86-64;  triple=x86_64-linux-android; extra+=(--disable-x86asm) ;;
    *) echo "unsupported ABI $abi" >&2; exit 1 ;;
  esac
  local build="$CACHE/build-$FFMPEG_VERSION-$abi" prefix="$CACHE/install-$FFMPEG_VERSION-$abi"
  rm -rf "$build" "$prefix"
  mkdir -p "$build"
  (
    cd "$build"
    "$SRC/configure" \
      --prefix="$prefix" \
      --target-os=android --arch="$arch" --cpu="$cpu" --enable-cross-compile \
      --sysroot="$TC/sysroot" \
      --cc="$TC/bin/$triple$API-clang" --cxx="$TC/bin/$triple$API-clang++" \
      --ar="$TC/bin/llvm-ar" --nm="$TC/bin/llvm-nm" --ranlib="$TC/bin/llvm-ranlib" \
      --strip="$TC/bin/llvm-strip" \
      --enable-shared --disable-static --enable-pic \
      --disable-everything --disable-autodetect --disable-programs --disable-doc \
      --disable-debug --disable-network --disable-avdevice --disable-avfilter --disable-postproc \
      --disable-gpl --disable-nonfree \
      --enable-avcodec --enable-avformat --enable-avutil --enable-swscale --enable-swresample \
      --enable-protocol=file \
      --enable-demuxer=asf \
      --enable-decoder=wmv3,vc1,wmav2 \
      --enable-decoder=h263 \
      --enable-parser=vc1 \
      --extra-cflags="-O2 -fstack-protector-strong" \
      --extra-ldflags="-Wl,-z,max-page-size=16384 -Wl,--build-id=sha1" \
      "${extra[@]}"
    make -j"$JOBS"
    make install
  )
  # Shared libs link with undefined symbols allowed; ff_* are library-internal, so any undefined
  # ff_ symbol is a missing object file. Fail here rather than at dlopen time.
  local undef
  undef="$("$TC/bin/llvm-nm" -D --undefined-only "$prefix"/lib/lib*.so | grep -E ' U ff_' || true)"
  if [[ -n "$undef" ]]; then echo "unresolved internal symbols:"$'\n'"$undef" >&2; exit 1; fi
  local out="$OUT_ROOT/$abi"
  rm -rf "$out"
  mkdir -p "$out/lib"
  cp -r "$prefix/include" "$out/include"
  for lib in avutil swresample swscale avcodec avformat; do
    "$TC/bin/llvm-strip" --strip-unneeded -o "$out/lib/lib$lib.so" "$prefix/lib/lib$lib.so"
  done
  echo "== $abi installed to $out"
  ls -la "$out/lib"
}

ABIS=("$@")
[[ ${#ABIS[@]} -gt 0 ]] || ABIS=(arm64-v8a x86_64)
for abi in "${ABIS[@]}"; do build_abi "$abi"; done
cp "$SRC/COPYING.LGPLv2.1" "$OUT_ROOT/COPYING.LGPLv2.1"
cat > "$OUT_ROOT/README.md" <<EOF
# Prebuilt FFmpeg $FFMPEG_VERSION (LGPL v2.1+)

Generated by \`../build_ffmpeg.sh\` from the unmodified upstream release
\`https://ffmpeg.org/releases/ffmpeg-$FFMPEG_VERSION.tar.xz\` (sha256 \`$FFMPEG_SHA256\`).
Minimal configuration: asf demuxer, wmv3/vc1/wmav2 decoders (+ h263, only to satisfy a vc1 link
dependency in 7.0.x), file protocol, swscale, swresample;
shared libraries for $(printf '%s ' "${ABIS[@]}")(API $API, NDK $(basename "$NDK")).
Do not edit; rerun the script instead. License: see COPYING.LGPLv2.1.
EOF
